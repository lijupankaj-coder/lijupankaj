create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.is_cms_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.audit_cms_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  row_data jsonb;
begin
  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  insert into public.audit_log (actor_id, operation, table_name, record_id)
  values ((select auth.uid()), tg_op, tg_table_name, coalesce(row_data ->> 'id', row_data ->> 'singleton', row_data ->> 'user_id'));
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create or replace function public.publish_site(new_snapshot jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  next_revision bigint;
  published_snapshot jsonb;
begin
  if not (select public.is_cms_admin()) then raise exception 'Not authorized'; end if;
  if jsonb_typeof(new_snapshot) <> 'object' then raise exception 'Invalid snapshot'; end if;
  select revision + 1 into next_revision from public.published_site where singleton for update;
  published_snapshot := jsonb_set(jsonb_set(new_snapshot, '{revision}', to_jsonb(next_revision)), '{publishedAt}', to_jsonb(now()));
  insert into public.publication_history (revision, snapshot, published_by) values (next_revision, published_snapshot, (select auth.uid()));
  update public.published_site set revision = next_revision, snapshot = published_snapshot, published_by = (select auth.uid()), published_at = now() where singleton;
  return published_snapshot;
end;
$$;

