create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 100),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,79}$'),
  position integer not null default 0 check (position between 0 and 10000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.projects (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,79}$'),
  name text not null check (char_length(name) between 1 and 160),
  client text not null default '' check (char_length(client) <= 160),
  year text not null default '' check (char_length(year) <= 40),
  category_id bigint references public.categories(id) on delete set null,
  overview text not null default '' check (char_length(overview) <= 1600),
  role text not null default '' check (char_length(role) <= 1200),
  contribution text not null default '' check (char_length(contribution) <= 1200),
  deliverables jsonb not null default '[]'::jsonb check (jsonb_typeof(deliverables) = 'array'),
  position integer not null default 0 check (position between 0 and 10000),
  featured boolean not null default false,
  status public.project_status not null default 'draft',
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.media_assets (
  id bigint generated by default as identity primary key,
  file_name text not null check (char_length(file_name) between 1 and 240),
  storage_path text not null unique check (char_length(storage_path) between 1 and 500),
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp', 'image/avif', 'image/svg+xml', 'application/pdf')),
  byte_size bigint not null check (byte_size > 0 and byte_size <= 15728640),
  content_hash text not null unique check (content_hash ~ '^[a-f0-9]{64}$'),
  alt_text text not null default '' check (char_length(alt_text) <= 240),
  width integer check (width is null or width between 1 and 30000),
  height integer check (height is null or height between 1 and 30000),
  variants jsonb not null default '{}'::jsonb check (jsonb_typeof(variants) = 'object'),
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.project_images (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  media_id bigint not null references public.media_assets(id) on delete restrict,
  caption text not null default '' check (char_length(caption) <= 300),
  alt_text text not null check (char_length(alt_text) between 4 and 240),
  position integer not null default 0 check (position between 0 and 10000),
  focal_x numeric(5,2) not null default 50 check (focal_x between 0 and 100),
  focal_y numeric(5,2) not null default 50 check (focal_y between 0 and 100),
  is_cover boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (project_id, media_id)
);

